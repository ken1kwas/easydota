/** Extracts `paths` from `vpk` into `dest` (each file only once). */
export function extract(vpk: VpkFile, paths: string | string[], dest: string = base.buildDir): void {
  for (const p of typeof paths === "string" ? [paths] : paths) {
    const full = path.join(dest, p);
    if (fs.existsSync(full)) continue;
    output.addText("&extracting_terminal", [p], { indent: true });
    if (!vpk.save(p, full)) log.writeWarning(`File not found in VPK: ${p}`);
  }
}

/** Dumps every file of `vpk` into `outputDir`. */
export function dump(vpk: VpkFile, outputDir: string, checkExists = true): void {
  for (const filepath of vpk) {
    const clean = filepath.trim().replace(/^["']+|["']+$/g, "").replace(/\\/g, "/").replace(/^\/+/, "");
    if (!clean) continue;
    const full = path.join(outputDir, clean);
    if (checkExists && fs.existsSync(full)) continue;
    vpk.save(filepath, full);
  }
}

/** Whether a VPK was generated by Minify (contains the metadata marker files). */
export function isMinifyPak(vpkPath: string): boolean {
  const markers = ["minify_mods.json", "minify_vpk_mods.txt", "minify_version.txt"];
  try {
    const pak = VpkFile.open(vpkPath);
    return markers.some((m) => pak.has(m));
  } catch {
    return false;
  }
}

/**
 * Standardizes metadata files for generated paks.
 * - modName: creates `{modName}.txt` (single mod patches)
 * - vpkMods: lines for minify_vpk_mods.txt
 * - extraLists: {filename: lines} additional metadata files
 */
export function dumpMetadata(targetDir: string, modName?: string, vpkMods?: string[], extraLists?: Record<string, string[]>): void {
  if (config.get("opt_out_vpk_metadata")) return;
  fs.mkdirSync(targetDir, { recursive: true });

  if (modName === undefined) {
    if (fs.existsSync(base.paths.modsConfig)) fs.copyFileSync(base.paths.modsConfig, path.join(targetDir, "minify_mods.json"));
    else fs.writeFileSync(path.join(targetDir, "minify_mods.json"), "{}");
  } else {
    fs.writeFileSync(path.join(targetDir, `${modName}.txt`), "");
  }

  if (vpkMods?.length) fs.writeFileSync(path.join(targetDir, "minify_vpk_mods.txt"), vpkMods.join("\n"), "utf8");
  for (const [filename, lines] of Object.entries(extraLists ?? {})) {
    fs.writeFileSync(path.join(targetDir, filename), lines.join("\n"), "utf8");
  }

  fs.writeFileSync(path.join(targetDir, "minify_version.txt"), base.VERSION, "utf8");
  if (fs.existsSync(C.dotaSteamInfPath)) fs.copyFileSync(C.dotaSteamInfPath, path.join(targetDir, "steam.inf"));
}
